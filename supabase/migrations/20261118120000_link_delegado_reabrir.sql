-- Cómo está cada alumno: lo vigente (lo cargado por el link y, en el casillero que
-- vino vacío, lo del programa), quién lo cargó, cuándo y en qué estado.
--   falta · programa (ya estaba y nadie lo tocó) · sin_enviar · enviado · aceptado
-- ROLLBACK: drop function if exists public.delegado_tablero(uuid);
create or replace function public.delegado_tablero(p_evento uuid)
returns table (
  id uuid, nombre text, division text, prog_acomp boolean, prog_musica boolean,
  acompanantes jsonb, musica text, hay_carga boolean, celular_id uuid, cargo text,
  persona text, cuando timestamptz, enviado boolean, traido boolean, estado text)
language sql
stable
security definer
set search_path = public
as $$
  select a.id, a.nombre, a.division,
         jsonb_array_length(a.acompanantes) > 0,
         a.musica <> '',
         case when g.alumno_id is not null and jsonb_array_length(g.acompanantes) > 0
              then g.acompanantes else a.acompanantes end,
         case when g.alumno_id is not null and g.musica <> '' then g.musica else a.musica end,
         g.alumno_id is not null,
         g.celular_id,
         c.nombre,
         case when c.id is not null then public.delegado_llave(c.nombre) end,
         g.updated_at,
         g.alumno_id is not null and g.enviado_at is not null,
         g.alumno_id is not null and g.traido_at is not null,
         case when g.alumno_id is null then
                case when jsonb_array_length(a.acompanantes) > 0 and a.musica <> ''
                     then 'programa' else 'falta' end
              when g.traido_at is not null  then 'aceptado'
              when g.enviado_at is not null then 'enviado'
              else 'sin_enviar' end
  from public.delegado_alumnos_datos(p_evento) a
  left join public.cargas_delegado g on g.evento_id = p_evento and g.alumno_id = a.id
  left join public.celulares_delegado c on c.id = g.celular_id;
$$;

-- El aviso para el programa. Null si no hay nada que avisar.
-- Salta cuando alguien envió después de la última vez que se trajo (también un
-- reenvío, si trae algo nuevo), o cuando el link venció con algo cargado que no se
-- envió y todavía no se trajo. Nunca por un guardado suelto.
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_aviso(p_evento uuid)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_link     public.links_delegado%rowtype;
  v_desde    timestamptz;
  v_vencido  boolean;
  v_enviaron text;
  v_no       text;
  v_faltan   integer;
begin
  select * into v_link from public.links_delegado l where l.evento_id = p_evento;
  if not found then return null; end if;
  v_desde   := coalesce(v_link.traido_at, '-infinity'::timestamptz);
  v_vencido := public.delegado_ahora() >= v_link.vence_at;

  -- Por persona: quién envió desde la última vez, y cuánto suyo falta traer.
  select string_agg(p.nombre || ' (' || n.cuantos || ')', ', ' order by p.envio)
    into v_enviaron
  from (
    select public.delegado_llave(c.nombre) as llave,
           min(c.nombre) as nombre, max(c.entregado_at) as envio
    from public.celulares_delegado c
    where c.evento_id = p_evento and c.entregado_at is not null
    group by public.delegado_llave(c.nombre)
    having max(c.entregado_at) > v_desde
  ) p
  join lateral (
    select count(*) as cuantos
    from public.cargas_delegado g
    join public.celulares_delegado d on d.id = g.celular_id
    where g.evento_id = p_evento and g.traido_at is null
      and public.delegado_llave(d.nombre) = p.llave
  ) n on true
  -- Quien envió y ya no tiene nada suyo para traer (otro lo corrigió) no figura.
  where n.cuantos > 0;

  -- Al vencer: lo cargado que nadie envió (o que se corrigió después de enviar).
  select string_agg(p.nombre || ' (cargó ' || p.cuantos || ')', ', ' order by p.entro)
    into v_no
  from (
    select min(c.nombre) as nombre, min(c.entro_at) as entro, count(*) as cuantos
    from public.cargas_delegado g
    join public.celulares_delegado c on c.id = g.celular_id
    where g.evento_id = p_evento and g.traido_at is null and g.enviado_at is null
    group by public.delegado_llave(c.nombre)
  ) p;

  if v_enviaron is null and not (v_vencido and v_no is not null) then return null; end if;

  select count(*) into v_faltan
  from public.delegado_tablero(p_evento) t where t.estado = 'falta';

  return 'Acompañantes y música para traer: ' || v_link.fiesta
      || case when v_enviaron is not null then ' · envió ' || v_enviaron else '' end
      || case when v_vencido and v_no is not null then ' · venció sin enviar: ' || v_no else '' end
      || case when v_faltan = 0 then ' · no falta nadie'
              when v_faltan = 1 then ' · falta 1 alumno'
              else ' · faltan ' || v_faltan || ' alumnos' end;
end;
$$;

-- ── 3. La página del delegado (sin usuario) ─────────────────────────────────

-- La fiesta y sus alumnos. Sin una sesión de este link no da ningún nombre de
-- alumno: solo de qué fiesta es y **quiénes ya entraron como delegados**, para que
-- el que vuelve desde otro celular toque su nombre.
-- Con sesión, de cada alumno da lo vigente, quién lo cargó y cuándo: hace falta para
-- corregirlo. Las claves de antes siguen (`de`, `cargo`, `prog_*`, `yo.entregado`).
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_lista(p_clave text, p_sesion text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_link       public.links_delegado%rowtype;
  v_cel        public.celulares_delegado%rowtype;
  v_ahora      timestamptz := public.delegado_ahora();
  v_base       jsonb;
  v_personas   integer;
  v_delegados  jsonb;
  v_yo         text;
  v_alumnos    jsonb;
  v_total      integer;
  v_cargados   integer;
  v_mios       integer;
  v_sin_enviar integer;
begin
  select * into v_link from public.links_delegado l where l.clave = p_clave;
  if p_clave is null or not found then
    return jsonb_build_object('ok', false, 'motivo', 'link');
  end if;

  v_base := jsonb_build_object(
    'fiesta',      v_link.fiesta,
    'vence_texto', public.delegado_texto_fecha(v_link.vence_at),
    'vencido',     v_ahora >= v_link.vence_at
  );
  if v_link.apagado then
    return v_base || jsonb_build_object('ok', false, 'motivo', 'apagado');
  end if;

  select * into v_cel from public.celulares_delegado c
  where c.evento_id = v_link.evento_id
    and p_sesion is not null
    and c.sesion_hash = encode(sha256(convert_to(p_sesion, 'UTF8')), 'hex');
  if not found then
    select count(*), coalesce(jsonb_agg(jsonb_build_object('nombre', p.nombre) order by p.entro), '[]'::jsonb)
      into v_personas, v_delegados
    from (
      select min(c.nombre) as nombre, min(c.entro_at) as entro
      from public.celulares_delegado c
      where c.evento_id = v_link.evento_id and c.sacado_at is null
      group by public.delegado_llave(c.nombre)
    ) p;
    return v_base || jsonb_build_object(
      'ok', false, 'motivo', 'entrar',
      'lleno', v_personas >= v_link.cupo,
      'delegados', v_delegados);
  end if;
  if v_cel.sacado_at is not null then
    return v_base || jsonb_build_object('ok', false, 'motivo', 'sacado');
  end if;
  v_yo := public.delegado_llave(v_cel.nombre);

  select coalesce(jsonb_agg(x.j order by x.sin_div, x.k_div, x.k_nom), '[]'::jsonb),
         count(*),
         count(*) filter (where x.estado <> 'falta'),
         count(*) filter (where x.mio),
         count(*) filter (where x.mio and x.estado = 'sin_enviar')
    into v_alumnos, v_total, v_cargados, v_mios, v_sin_enviar
  from (
    select
      (t.division = '')                 as sin_div,
      public.delegado_llave(t.division) as k_div,
      public.delegado_llave(t.nombre)   as k_nom,
      t.estado,
      (t.hay_carga and t.persona = v_yo) as mio,
      jsonb_build_object(
        'id',           t.id,
        'nombre',       t.nombre,
        'division',     t.division,
        'prog_acomp',   t.prog_acomp,
        'prog_musica',  t.prog_musica,
        'de', case
                when not t.hay_carga then
                  case when t.prog_acomp and t.prog_musica then 'programa' else 'libre' end
                when t.celular_id is null then 'suelto'
                when t.persona = v_yo     then 'mio'
                else 'otro'
              end,
        'cargo',        t.cargo,
        'acompanantes', t.acompanantes,
        'musica',       t.musica,
        'estado',       t.estado,
        'cuando_texto', case when t.hay_carga then public.delegado_texto_corto(t.cuando) end,
        'mio',          (t.hay_carga and t.persona = v_yo),
        'en_programa',  (t.prog_acomp or t.prog_musica)
      ) as j
    from public.delegado_tablero(v_link.evento_id) t
  ) x;

  return v_base || jsonb_build_object(
    'ok',       true,
    'yo',       jsonb_build_object(
                  'nombre',      v_cel.nombre,
                  'entregado',   v_cel.entregado_at is not null,
                  'envio_texto', case when v_cel.entregado_at is not null
                                      then public.delegado_texto_corto(v_cel.entregado_at) end,
                  'sin_enviar',  v_sin_enviar),
    'total',    v_total,
    'cargados', v_cargados,
    'faltan',   v_total - v_cargados,
    'mios',     v_mios,
    'alumnos',  v_alumnos
  );
end;
$$;

-- Entrar. **El delegado es la persona, no el celular**: quien escribe (o toca) un
-- nombre que ya entró sigue con lo suyo desde otro aparato, aunque el cupo esté
-- lleno. Un nombre nuevo entra mientras haya lugar; el cupo cuenta personas.
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_entrar(p_clave text, p_nombre text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link     public.links_delegado%rowtype;
  v_ahora    timestamptz := public.delegado_ahora();
  v_nombre   text := upper(public.delegado_un_espacio(p_nombre));
  v_llave    text;
  v_ya       text;
  v_envio    timestamptz;
  v_aparatos integer;
  v_sacada   boolean;
  v_personas integer;
  v_sesion   text;
begin
  -- La fila del link se toma para escribir: todo lo de un link va de a uno.
  select * into v_link from public.links_delegado l where l.clave = p_clave for update;
  if p_clave is null or not found then
    return jsonb_build_object('ok', false, 'motivo', 'link');
  end if;
  if v_link.apagado then
    return jsonb_build_object('ok', false, 'motivo', 'apagado');
  end if;
  if v_ahora >= v_link.vence_at then
    return jsonb_build_object('ok', false, 'motivo', 'vencido');
  end if;
  if char_length(v_nombre) < 5 or char_length(v_nombre) > 60
     or v_nombre !~ '[A-ZÁÉÍÓÚÜÑ]{2}' or position(' ' in v_nombre) = 0 then
    return jsonb_build_object('ok', false, 'motivo', 'nombre');
  end if;
  v_llave := public.delegado_llave(v_nombre);

  select min(c.nombre), max(c.entregado_at), count(*), bool_or(c.sacado_at is not null)
    into v_ya, v_envio, v_aparatos, v_sacada
  from public.celulares_delegado c
  where c.evento_id = v_link.evento_id and public.delegado_llave(c.nombre) = v_llave;

  if v_aparatos > 0 then
    if v_sacada then
      return jsonb_build_object('ok', false, 'motivo', 'sacado');
    end if;
    -- Un tope para que nadie llene la tabla entrando mil veces con el mismo nombre.
    if v_aparatos >= 30 then
      return jsonb_build_object('ok', false, 'motivo', 'lleno');
    end if;
    v_nombre := v_ya;
  else
    select count(distinct public.delegado_llave(c.nombre)) into v_personas
    from public.celulares_delegado c
    where c.evento_id = v_link.evento_id and c.sacado_at is null;
    if v_personas >= v_link.cupo then
      return jsonb_build_object('ok', false, 'motivo', 'lleno');
    end if;
    v_envio := null;
  end if;

  v_sesion := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
  insert into public.celulares_delegado (evento_id, sesion_hash, nombre, entro_at, entregado_at)
  values (v_link.evento_id, encode(sha256(convert_to(v_sesion, 'UTF8')), 'hex'), v_nombre, v_ahora, v_envio);
  return jsonb_build_object('ok', true, 'sesion', v_sesion);
end;
$$;

-- Guardar un alumno. **Todos corrigen todo**: lo que cargó otro, lo ya enviado y lo
-- que ya está en el programa se pueden corregir (lo del programa no cambia hasta que
-- el jefe lo acepta al traer). Las trabas que quedan, en orden:
--   el link (existe, prendido, a tiempo) · el celular (de este link, sin sacar) · el
--   alumno (activo y de esta fiesta) · hasta 2 acompañantes de hasta 80 letras ·
--   música de hasta 300.
-- Vaciar los dos casilleros saca lo cargado por el link (lo del programa queda).
-- Cada guardado queda en el historial, y vuelve a quedar "sin enviar" y "sin traer".
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_guardar(
  p_clave text, p_sesion text, p_alumno uuid, p_acompanantes jsonb, p_musica text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link    public.links_delegado%rowtype;
  v_cel     public.celulares_delegado%rowtype;
  v_hay     boolean;
  v_ahora   timestamptz := public.delegado_ahora();
  v_nombres jsonb;
  v_musica  text;
begin
  select * into v_link from public.links_delegado l where l.clave = p_clave for update;
  if p_clave is null or not found then
    return jsonb_build_object('ok', false, 'motivo', 'link');
  end if;
  if v_link.apagado then
    return jsonb_build_object('ok', false, 'motivo', 'apagado');
  end if;
  if v_ahora >= v_link.vence_at then
    return jsonb_build_object('ok', false, 'motivo', 'vencido');
  end if;

  select * into v_cel from public.celulares_delegado c
  where c.evento_id = v_link.evento_id
    and p_sesion is not null
    and c.sesion_hash = encode(sha256(convert_to(p_sesion, 'UTF8')), 'hex');
  if not found then
    return jsonb_build_object('ok', false, 'motivo', 'sesion');
  end if;
  if v_cel.sacado_at is not null then
    return jsonb_build_object('ok', false, 'motivo', 'sacado');
  end if;

  if p_alumno is null or not exists (
    select 1 from public.delegado_alumnos(v_link.evento_id) a where a.id = p_alumno
  ) then
    return jsonb_build_object('ok', false, 'motivo', 'alumno');
  end if;

  if p_acompanantes is not null and jsonb_typeof(p_acompanantes) <> 'array' then
    return jsonb_build_object('ok', false, 'motivo', 'formato');
  end if;
  if exists (
    select 1 from jsonb_array_elements(coalesce(p_acompanantes, '[]'::jsonb)) e
    where jsonb_typeof(e) <> 'string'
  ) then
    return jsonb_build_object('ok', false, 'motivo', 'formato');
  end if;
  v_nombres := public.delegado_nombres(coalesce(p_acompanantes, '[]'::jsonb));
  if jsonb_array_length(v_nombres) > 2 then
    return jsonb_build_object('ok', false, 'motivo', 'tope');
  end if;
  if exists (select 1 from jsonb_array_elements_text(v_nombres) e where char_length(e) > 80) then
    return jsonb_build_object('ok', false, 'motivo', 'largo', 'campo', 'acompanantes');
  end if;
  -- En un solo renglón, como la música que entra por el Excel.
  v_musica := public.delegado_un_espacio(p_musica);
  if char_length(v_musica) > 300 then
    return jsonb_build_object('ok', false, 'motivo', 'largo', 'campo', 'musica');
  end if;

  v_hay := exists (
    select 1 from public.cargas_delegado g
    where g.evento_id = v_link.evento_id and g.alumno_id = p_alumno);

  if jsonb_array_length(v_nombres) = 0 and v_musica = '' then
    if v_hay then
      delete from public.cargas_delegado g
      where g.evento_id = v_link.evento_id and g.alumno_id = p_alumno;
      insert into public.cambios_delegado (evento_id, alumno_id, celular_id, quien, que, created_at)
      values (v_link.evento_id, p_alumno, v_cel.id, v_cel.nombre, 'vacio', v_ahora);
      return jsonb_build_object('ok', true, 'libre', true);
    end if;
    return jsonb_build_object('ok', false, 'motivo', 'vacio');
  end if;

  insert into public.cargas_delegado
    (evento_id, alumno_id, celular_id, acompanantes, musica, updated_at)
  values (v_link.evento_id, p_alumno, v_cel.id, v_nombres, v_musica, v_ahora)
  on conflict (evento_id, alumno_id) do update
    set celular_id   = excluded.celular_id,
        acompanantes = excluded.acompanantes,
        musica       = excluded.musica,
        updated_at   = excluded.updated_at,
        traido_at    = null,
        enviado_at   = null;
  insert into public.cambios_delegado
    (evento_id, alumno_id, celular_id, quien, que, acompanantes, musica, created_at)
  values (v_link.evento_id, p_alumno, v_cel.id, v_cel.nombre, 'guardo', v_nombres, v_musica, v_ahora);
  return jsonb_build_object('ok', true);
end;
$$;

-- El envío: **no cierra nada**. Marca como enviado lo que esa persona tiene sin
-- enviar y avisa al programa. Se puede enviar las veces que haga falta; sin nada
-- nuevo no cambia nada (`ya`).
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_entregar(p_clave text, p_sesion text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link    public.links_delegado%rowtype;
  v_cel     public.celulares_delegado%rowtype;
  v_ahora   timestamptz := public.delegado_ahora();
  v_llave   text;
  v_suyas   integer;
  v_nuevas  integer;
begin
  select * into v_link from public.links_delegado l where l.clave = p_clave for update;
  if p_clave is null or not found then
    return jsonb_build_object('ok', false, 'motivo', 'link');
  end if;
  if v_link.apagado then
    return jsonb_build_object('ok', false, 'motivo', 'apagado');
  end if;
  if v_ahora >= v_link.vence_at then
    return jsonb_build_object('ok', false, 'motivo', 'vencido');
  end if;

  select * into v_cel from public.celulares_delegado c
  where c.evento_id = v_link.evento_id
    and p_sesion is not null
    and c.sesion_hash = encode(sha256(convert_to(p_sesion, 'UTF8')), 'hex');
  if not found then
    return jsonb_build_object('ok', false, 'motivo', 'sesion');
  end if;
  if v_cel.sacado_at is not null then
    return jsonb_build_object('ok', false, 'motivo', 'sacado');
  end if;
  v_llave := public.delegado_llave(v_cel.nombre);

  select count(*), count(*) filter (where g.enviado_at is null)
    into v_suyas, v_nuevas
  from public.cargas_delegado g
  join public.celulares_delegado c on c.id = g.celular_id
  where g.evento_id = v_link.evento_id and public.delegado_llave(c.nombre) = v_llave;
  if v_suyas = 0 then
    return jsonb_build_object('ok', false, 'motivo', 'nada');
  end if;
  if v_nuevas = 0 then
    return jsonb_build_object('ok', true, 'ya', true);
  end if;

  update public.cargas_delegado g set enviado_at = v_ahora
  where g.evento_id = v_link.evento_id and g.enviado_at is null
    and g.celular_id in (
      select c.id from public.celulares_delegado c
      where c.evento_id = v_link.evento_id and public.delegado_llave(c.nombre) = v_llave);
  update public.celulares_delegado c set entregado_at = v_ahora
  where c.evento_id = v_link.evento_id and public.delegado_llave(c.nombre) = v_llave;
  return jsonb_build_object('ok', true);
end;
$$;

