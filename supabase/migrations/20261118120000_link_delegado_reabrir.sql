-- Cómo está el link. A lo de antes le suma los delegados **por persona** (los
-- `celulares` siguen, para la versión anterior) y cuánto hay en cada estado.
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_link(p_evento uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_link      public.links_delegado%rowtype;
  v_ahora     timestamptz := public.delegado_ahora();
  v_celulares jsonb;
  v_delegados jsonb;
  v_total     integer;
  v_programa  integer;
  v_cargados  integer;
  v_sin       integer;
  v_enviados  integer;
  v_aceptados integer;
  v_faltan    integer;
begin
  if auth.role() is distinct from 'authenticated' then
    raise exception 'El link del delegado se maneja con usuario' using errcode = '42501';
  end if;
  select * into v_link from public.links_delegado l where l.evento_id = p_evento;
  if not found then
    return jsonb_build_object('ok', false, 'motivo', 'sin_link');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id',              c.id,
           'nombre',          c.nombre,
           'entro_texto',     public.delegado_texto_fecha(c.entro_at),
           'cargados',        (select count(*) from public.cargas_delegado g where g.celular_id = c.id),
           'entregado',       c.entregado_at is not null,
           'entregado_texto', case when c.entregado_at is not null
                                   then public.delegado_texto_fecha(c.entregado_at) end,
           'sacado',          c.sacado_at is not null
         ) order by c.entro_at, c.nombre), '[]'::jsonb)
    into v_celulares
  from public.celulares_delegado c where c.evento_id = p_evento;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id',           p.id,
           'nombre',       p.nombre,
           'entro_texto',  public.delegado_texto_corto(p.entro),
           'aparatos',     p.aparatos,
           'cargados',     n.cargados,
           'sin_enviar',   n.sin_enviar,
           'envio_texto',  case when p.envio is not null then public.delegado_texto_corto(p.envio) end,
           'sacado',       p.sacado
         ) order by p.entro, p.nombre), '[]'::jsonb)
    into v_delegados
  from (
    select public.delegado_llave(c.nombre) as llave,
           (array_agg(c.id order by c.entro_at, c.id))[1] as id,
           min(c.nombre) as nombre, min(c.entro_at) as entro, count(*) as aparatos,
           max(c.entregado_at) as envio, bool_or(c.sacado_at is not null) as sacado
    from public.celulares_delegado c
    where c.evento_id = p_evento
    group by public.delegado_llave(c.nombre)
  ) p
  join lateral (
    select count(*) as cargados,
           count(*) filter (where g.enviado_at is null and g.traido_at is null) as sin_enviar
    from public.cargas_delegado g
    join public.celulares_delegado d on d.id = g.celular_id
    where g.evento_id = p_evento and public.delegado_llave(d.nombre) = p.llave
  ) n on true;

  select count(*),
         count(*) filter (where t.estado = 'programa'),
         count(*) filter (where t.hay_carga and not (t.prog_acomp and t.prog_musica)),
         count(*) filter (where t.estado = 'sin_enviar'),
         count(*) filter (where t.estado = 'enviado'),
         count(*) filter (where t.estado = 'aceptado'),
         count(*) filter (where t.estado = 'falta')
    into v_total, v_programa, v_cargados, v_sin, v_enviados, v_aceptados, v_faltan
  from public.delegado_tablero(p_evento) t;

  return jsonb_build_object(
    'ok',          true,
    'clave',       v_link.clave,
    'vence_texto', public.delegado_texto_fecha(v_link.vence_at),
    'vence_local', to_char(v_link.vence_at at time zone 'America/Argentina/Buenos_Aires', 'YYYY-MM-DD HH24:MI'),
    'estado',      case when v_link.apagado then 'apagado'
                        when v_ahora >= v_link.vence_at then 'vencido'
                        else 'abierto' end,
    'cupo',        v_link.cupo,
    'celulares',   v_celulares,
    'delegados',   v_delegados,
    'total',       v_total,
    'en_programa', v_programa,
    'cargados',    v_cargados,
    'faltan',      v_faltan,
    'sin_enviar',  v_sin,
    'enviados',    v_enviados,
    'aceptados',   v_aceptados,
    'aviso',       public.delegado_aviso(p_evento)
  );
end;
$$;

-- Lo que cambia el jefe. Como antes: apagar, prender, el límite, el cupo, sacar,
-- reabrirle el envío (para la versión anterior) y anotar qué trajo. Lo nuevo:
--   · `vence` con una fecha futura también prende el link (REABRIR HASTA…);
--   · sacar y reabrir valen para la persona, en todos sus aparatos;
--   · `sacar_dejando` conserva quién cargó cada cosa;
--   · `readmitir`: deja entrar de nuevo a quien se había sacado;
--   · `traido` y `sacar_borrando` quedan en el historial.
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_link_cambiar(p_evento uuid, p_accion text, p_valor text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_link    public.links_delegado%rowtype;
  v_ahora   timestamptz := public.delegado_ahora();
  v_vence   timestamptz;
  v_cupo    integer;
  v_persona text;
begin
  if auth.role() is distinct from 'authenticated' then
    raise exception 'El link del delegado se maneja con usuario' using errcode = '42501';
  end if;
  select * into v_link from public.links_delegado l where l.evento_id = p_evento for update;
  if not found then
    return jsonb_build_object('ok', false, 'motivo', 'sin_link');
  end if;

  if p_accion in ('sacar_dejando', 'sacar_borrando', 'reabrir', 'readmitir') then
    if p_valor is null or p_valor !~ '^[0-9a-fA-F-]{36}$' then
      return jsonb_build_object('ok', false, 'motivo', 'celular');
    end if;
    select public.delegado_llave(c.nombre) into v_persona from public.celulares_delegado c
    where c.id = p_valor::uuid and c.evento_id = p_evento;
    if not found then
      return jsonb_build_object('ok', false, 'motivo', 'celular');
    end if;
  end if;

  if p_accion = 'apagar' then
    update public.links_delegado set apagado = true where evento_id = p_evento;
  elsif p_accion = 'prender' then
    update public.links_delegado set apagado = false where evento_id = p_evento;
  elsif p_accion = 'vence' then
    v_vence := public.delegado_vence(p_valor);
    if v_vence is null then
      return jsonb_build_object('ok', false, 'motivo', 'fecha');
    end if;
    update public.links_delegado
       set vence_at = v_vence,
           apagado  = case when v_vence > v_ahora then false else apagado end
     where evento_id = p_evento;
  elsif p_accion = 'cupo' then
    if p_valor is null or p_valor !~ '^[1-5]$' then
      return jsonb_build_object('ok', false, 'motivo', 'cupo');
    end if;
    v_cupo := p_valor::integer;
    update public.links_delegado set cupo = v_cupo where evento_id = p_evento;
  elsif p_accion = 'sacar_dejando' then
    update public.celulares_delegado c set sacado_at = v_ahora
    where c.evento_id = p_evento and c.sacado_at is null
      and public.delegado_llave(c.nombre) = v_persona;
  elsif p_accion = 'sacar_borrando' then
    update public.celulares_delegado c set sacado_at = v_ahora
    where c.evento_id = p_evento and c.sacado_at is null
      and public.delegado_llave(c.nombre) = v_persona;
    insert into public.cambios_delegado
      (evento_id, alumno_id, celular_id, quien, que, acompanantes, musica, created_at)
    select g.evento_id, g.alumno_id, null, 'Junior Eventos', 'borrado', g.acompanantes, g.musica, v_ahora
      from public.cargas_delegado g
      join public.celulares_delegado c on c.id = g.celular_id
     where g.evento_id = p_evento and public.delegado_llave(c.nombre) = v_persona;
    delete from public.cargas_delegado g
     where g.evento_id = p_evento
       and g.celular_id in (
         select c.id from public.celulares_delegado c
         where c.evento_id = p_evento and public.delegado_llave(c.nombre) = v_persona);
  elsif p_accion = 'reabrir' then
    update public.celulares_delegado c set entregado_at = null
    where c.evento_id = p_evento and c.sacado_at is null
      and public.delegado_llave(c.nombre) = v_persona;
  elsif p_accion = 'readmitir' then
    update public.celulares_delegado c set sacado_at = null
    where c.evento_id = p_evento and public.delegado_llave(c.nombre) = v_persona;
  elsif p_accion = 'traido' then
    -- p_valor: los alumnos que se trajeron a la grilla, como lista JSON de ids.
    if p_valor is not null then
      begin
        insert into public.cambios_delegado
          (evento_id, alumno_id, celular_id, quien, que, acompanantes, musica, created_at)
        select g.evento_id, g.alumno_id, null, 'Junior Eventos', 'aceptado', g.acompanantes, g.musica, v_ahora
          from public.cargas_delegado g
         where g.evento_id = p_evento and g.traido_at is null
           and g.alumno_id in (select e::uuid from jsonb_array_elements_text(p_valor::jsonb) e);
        update public.cargas_delegado g set traido_at = v_ahora
        where g.evento_id = p_evento
          and g.alumno_id in (select e::uuid from jsonb_array_elements_text(p_valor::jsonb) e);
      exception when others then
        return jsonb_build_object('ok', false, 'motivo', 'alumnos');
      end;
    end if;
    update public.links_delegado set traido_at = v_ahora where evento_id = p_evento;
  else
    return jsonb_build_object('ok', false, 'motivo', 'accion');
  end if;

  update public.links_delegado set updated_at = v_ahora where evento_id = p_evento;
  return jsonb_build_object('ok', true);
end;
$$;

-- Lo cargado, para traer. A lo de antes le suma cuándo se cargó, si esa carga está
-- enviada y si ya se trajo. **`entregado` pasa a decir si esa carga está enviada**
-- (antes, si su celular había enviado): lo corregido después de enviar va aparte,
-- como "sin enviar", también en la versión anterior del programa.
-- ROLLBACK: (vuelve la del archivo 20261113120000_link_delegado.sql)
create or replace function public.delegado_cargas(p_evento uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if auth.role() is distinct from 'authenticated' then
    raise exception 'El link del delegado se maneja con usuario' using errcode = '42501';
  end if;
  return (
    select coalesce(jsonb_agg(jsonb_build_object(
             'alumno_id',    g.alumno_id,
             'alumno',       coalesce(a.nombre, public.delegado_un_espacio(k.nombre_alumno)),
             'division',     coalesce(a.division, public.delegado_un_espacio(k.curso_division)),
             'activo',       a.id is not null,
             'acompanantes', g.acompanantes,
             'musica',       g.musica,
             'cargo',        c.nombre,
             'entregado',    g.enviado_at is not null,
             'enviado',      g.enviado_at is not null,
             'traido',       g.traido_at is not null,
             'cuando_texto', public.delegado_texto_corto(g.updated_at),
             'suelto',       g.celular_id is null
           ) order by (coalesce(a.division, '') = ''),
                      public.delegado_llave(coalesce(a.division, k.curso_division)),
                      public.delegado_llave(coalesce(a.nombre, k.nombre_alumno))),
           '[]'::jsonb)
    from public.cargas_delegado g
    left join public.delegado_alumnos(p_evento) a on a.id = g.alumno_id
    left join public.contratos_alumnos k on k.id = g.alumno_id
    left join public.celulares_delegado c on c.id = g.celular_id
    where g.evento_id = p_evento
  );
end;
$$;

